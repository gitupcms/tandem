package tandem.ksp

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.KSDeclaration
import com.google.devtools.ksp.symbol.KSFile

/** One action subclass plus its primary-constructor parameters, in declaration order. */
internal class ActionEntry(val subclass: KSClassDeclaration, val fields: List<Field>)

/** The generated object's name: enclosing type names, the interface name, then `Introspection`. */
internal fun introspectionName(declaration: KSClassDeclaration): String {
    val names = generateSequence<KSDeclaration>(declaration) { it.parentDeclaration }
        .map { it.simpleName.asString() }
        .toList()
        .asReversed()
    return names.joinToString("") + "Introspection"
}

/** Writes `fun X.toJson(): tandem.Json` in [packageName]. */
internal fun writeStateJson(
    codeGenerator: CodeGenerator,
    record: Wire.Record,
    packageName: String,
    source: KSFile?,
) {
    val receiver = record.type.removePrefix(if (packageName.isEmpty()) "" else "$packageName.")
    val importedPackages = linkedSetOf<String>()
    val fields = StringBuilder()
    for (field in record.fields) {
        val name = field.name
        if (field.nullable) {
            val value = (field.wire as Wire.Maybe).value
            val encoded = encode("it", value, packageName, importedPackages)
            fields.appendLine("    $name?.let { fields[\"$name\"] = $encoded }")
        } else {
            fields.appendLine("    fields[\"$name\"] = ${encode(name, field.wire, packageName, importedPackages)}")
        }
    }
    val imports = importedPackages.filter { it.isNotEmpty() && it != packageName }.sorted()
        .joinToString("") { "import $it.toJson\n" }

    val text = buildString {
        appendLine("// Generated by tandem-ksp from @Introspectable. Do not edit.")
        appendLine("package $packageName")
        if (imports.isNotEmpty()) {
            appendLine()
            append(imports)
        }
        appendLine()
        appendLine("/**")
        appendLine(" * Wire JSON for [$receiver]: one field per primary-constructor property, named exactly as")
        appendLine(" * the property. A null property is left out instead of written as JSON null.")
        appendLine(" */")
        appendLine("fun $receiver.toJson(): tandem.Json {")
        appendLine("    val fields = linkedMapOf<String, tandem.Json>()")
        append(fields)
        appendLine("    return tandem.Json.Obj(fields)")
        appendLine("}")
    }
    write(codeGenerator, packageName, record.type.replace('.', '_') + "ToJson", text, source)
}

/** Writes the `object <Name>Introspection { fun actions(send: (T) -> Unit) }` for one interface. */
internal fun writeActions(
    codeGenerator: CodeGenerator,
    declaration: KSClassDeclaration,
    entries: List<ActionEntry>,
    packageName: String,
) {
    val qualified = declaration.qualifiedName!!.asString()
    val receiver = qualified.removePrefix(if (packageName.isEmpty()) "" else "$packageName.")
    val objectName = introspectionName(declaration)
    val body = StringBuilder()
    entries.forEachIndexed { index, entry ->
        val className = entry.subclass.simpleName.asString()
        val send = buildSend(entry, packageName)
        val separator = if (index == entries.lastIndex) "" else ","
        if (entry.fields.isEmpty()) {
            body.appendLine("        tandem.Action(name = \"$className\") { $send }$separator")
        } else {
            val schemaText = schema(Wire.Record(entry.subclass.qualifiedName!!.asString(), packageName, entry.fields))
            body.appendLine("        tandem.Action(")
            body.appendLine("            name = \"$className\",")
            body.appendLine("            input = $schemaText,")
            body.appendLine("        ) { input -> $send }$separator")
        }
    }

    val text = buildString {
        appendLine("// Generated by tandem-ksp from @IntrospectableActions. Do not edit.")
        appendLine("package $packageName")
        appendLine()
        appendLine("/**")
        appendLine(" * Kit actions for [$receiver], in declaration order.")
        appendLine(" *")
        appendLine(" * Naming: the object is every enclosing type's simple name, then the interface's simple")
        appendLine(" * name, then `Introspection`; here that makes `$objectName`. An action is named after its")
        appendLine(" * subclass, and its input is the subclass's primary constructor, in order; a subclass")
        appendLine(" * without parameters has no input.")
        appendLine(" */")
        appendLine("object $objectName {")
        appendLine("    fun actions(send: ($receiver) -> Unit): List<tandem.Action> = listOf(")
        append(body)
        appendLine("    )")
        appendLine("}")
        appendLine()
        appendLine("private fun tandem.Json?.tandemField(key: String): tandem.Json? =")
        appendLine("    (this as? tandem.Json.Obj)?.fields?.get(key)")
        appendLine()
        appendLine("private fun tandem.Json.tandemItems(): List<tandem.Json> =")
        appendLine("    (this as? tandem.Json.Arr)?.items ?: emptyList()")
    }
    write(codeGenerator, packageName, objectName, text, source(declaration), aggregating = true)
}

private fun source(declaration: KSClassDeclaration): KSFile? = declaration.containingFile

private fun buildSend(entry: ActionEntry, packageName: String): String {
    val constructor = relative(entry.subclass.qualifiedName!!.asString(), packageName)
    if (entry.fields.isEmpty()) return "send($constructor)"
    val arguments = entry.fields.joinToString(", ") { field ->
        val lookup = "input.tandemField(\"${field.name}\")"
        if (field.nullable) {
            "$lookup?.let { ${decode("it", (field.wire as Wire.Maybe).value, packageName)} }"
        } else {
            decode("$lookup!!", field.wire, packageName)
        }
    }
    return "send($constructor($arguments))"
}

/** Strips [packageName] when the type lives in the generated file's own package. */
private fun relative(qualifiedName: String, packageName: String): String =
    if (packageName.isEmpty()) qualifiedName else qualifiedName.removePrefix("$packageName.")

/** Turns a checked `tandem.Json` expression into the Kotlin value of [wire]. */
private fun decode(expression: String, wire: Wire, packageName: String): String {
    var nested = 0
    fun decodeAt(expr: String, shape: Wire): String = when (shape) {
        Wire.Text -> "$expr.string!!"
        is Wire.Integer ->
            if (shape.kotlinType == "kotlin.Long") "$expr.long!!" else "$expr.long!!.toInt()"

        Wire.Flag -> "$expr.bool!!"
        is Wire.Choice -> "${relative(shape.type, packageName)}.valueOf($expr.string!!)"
        is Wire.Sequence -> "$expr.tandemItems().map { ${decodeAt("it", shape.item)} }"
        is Wire.Record -> {
            val temp = "tandemValue${nested++}"
            val arguments = shape.fields.joinToString(", ") { field ->
                val lookup = "$temp.tandemField(\"${field.name}\")"
                if (field.nullable) {
                    "$lookup?.let { ${decodeAt("it", (field.wire as Wire.Maybe).value)} }"
                } else {
                    decodeAt("$lookup!!", field.wire)
                }
            }
            "$expr.let { $temp -> ${relative(shape.type, packageName)}($arguments) }"
        }

        is Wire.Maybe -> error("nullable values are unwrapped by the caller")
    }
    return decodeAt(expression, wire)
}

/** The `tandem.Schema` expression for one wire shape. */
internal fun schema(wire: Wire): String = when (wire) {
    Wire.Text -> "tandem.Schema.string"
    is Wire.Integer -> "tandem.Schema.integer"
    Wire.Flag -> "tandem.Schema.boolean"
    is Wire.Choice -> "tandem.Schema.enum(${wire.constants.joinToString(", ") { "\"$it\"" }})"
    is Wire.Sequence -> "tandem.Schema.array(${schema(wire.item)})"
    is Wire.Record -> {
        val properties = wire.fields.joinToString(", ") { "\"${it.name}\" to ${schema(it.wire)}" }
        val required = wire.fields.filter { !it.nullable }.map { it.name }
        if (required.isEmpty()) "tandem.Schema.obj($properties)"
        else "tandem.Schema.obj($properties, required = listOf(${required.joinToString(", ") { "\"$it\"" }}))"
    }

    is Wire.Maybe -> schema(wire.value)
}

/** The `tandem.Json` expression for one Kotlin expression of [wire], recording needed imports. */
private fun encode(
    expression: String,
    wire: Wire,
    targetPackage: String,
    importedPackages: MutableSet<String>,
): String = when (wire) {
    Wire.Text -> "tandem.Json.Str($expression)"
    is Wire.Integer ->
        if (wire.kotlinType == "kotlin.Long") "tandem.Json.Integer($expression)"
        else "tandem.Json.Integer($expression.toLong())"

    Wire.Flag -> "tandem.Json.Bool($expression)"
    is Wire.Choice -> "tandem.Json.Str($expression.name)"
    is Wire.Record -> {
        if (wire.packageName.isNotEmpty() && wire.packageName != targetPackage) importedPackages += wire.packageName
        "$expression.toJson()"
    }

    is Wire.Sequence -> "tandem.Json.Arr($expression.map { ${encode("it", wire.item, targetPackage, importedPackages)} })"
    is Wire.Maybe -> error("nullable values are unwrapped by the caller")
}

private fun write(
    codeGenerator: CodeGenerator,
    packageName: String,
    fileName: String,
    text: String,
    source: KSFile?,
    aggregating: Boolean = false,
) {
    val dependencies = if (source == null) Dependencies(false) else Dependencies(aggregating, source)
    codeGenerator.createNewFile(dependencies, packageName, fileName).use { it.write(text.toByteArray()) }
}
